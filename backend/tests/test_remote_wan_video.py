@pytest.mark.asyncio
async def test_remote_wan_successful_generation(tmp_path):
    provider = RemoteWanVideoProvider(
        remote_url="http://mock-gpu-worker:8002",
        api_key="secret-bearer-key",
        timeout_seconds=30
    )
    gen = Generation(
        id="moviq-gen-remote-test-1",
        original_prompt="A massive ancient temple emerging from a dense jungle at sunrise",
        enhanced_prompt="Cinematic 35mm shot of a massive ancient temple emerging from a dense jungle at sunrise...",
        negative_prompt="blurry",
        aspect_ratio="16:9",
        duration="5s"
    )

    mock_post_resp = MagicMock()
    mock_post_resp.status_code = 200
    mock_post_resp.json.return_value = {
        "status": "completed",
        "generation_id": "moviq-gen-remote-test-1",
        "video_url": "/videos/moviq_moviq-gen-remote-test-1.mp4"
    }

    mock_dl_resp = MagicMock()
    mock_dl_resp.status_code = 200
    mock_dl_resp.content = b"fake binary MP4 video payload generated by remote Wan2.1 GPU worker"

    mock_client = AsyncMock()
    mock_client.post = AsyncMock(return_value=mock_post_resp)
    mock_client.get = AsyncMock(return_value=mock_dl_resp)

    mock_cm = AsyncMock()
    mock_cm.__aenter__.return_value = mock_client

    with patch("httpx.AsyncClient", return_value=mock_cm):
        job_id = await provider.submit_generation(gen)
        assert job_id.startswith("remote-wan-job-")

        import asyncio
        await asyncio.sleep(0.4)

        # Verify POST payload sent to remote worker contains ENHANCED prompt & Bearer token
        mock_client.post.assert_called_once()
        call_kwargs = mock_client.post.call_args
        url_arg = call_kwargs[0][0]
        json_kw = call_kwargs[1]["json"]
        headers_kw = call_kwargs[1]["headers"]

        assert url_arg == "http://mock-gpu-worker:8002/generate"
        assert json_kw["prompt"] == gen.enhanced_prompt
        assert headers_kw["Authorization"] == "Bearer secret-bearer-key"

        status, pct = await provider.check_status(job_id)
        assert status == GenerationStatus.COMPLETED

        result = await provider.get_result(job_id)
        assert result["video_url"] == "/api/v1/generations/moviq-gen-remote-test-1/video"

        # Verify local file saved
        filepath = os.path.join(os.getcwd(), "generated", "moviq_moviq-gen-remote-test-1.mp4")
        assert os.path.exists(filepath)


