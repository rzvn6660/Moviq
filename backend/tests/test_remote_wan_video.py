@pytest.mark.asyncio
async def test_remote_wan_http_500_error_preservation():
    provider = RemoteWanVideoProvider(remote_url="http://mock-gpu-worker:8002")
    gen = Generation(id="gen-http-500", original_prompt="test")

    mock_post_resp = MagicMock()
    mock_post_resp.status_code = 500
    mock_post_resp.text = '{"detail": "Wan generation failed: NameError: name \'pipe\' is not defined"}'

    mock_client = AsyncMock()
    mock_client.post = AsyncMock(return_value=mock_post_resp)

    mock_cm = AsyncMock()
    mock_cm.__aenter__.return_value = mock_client

    with patch("httpx.AsyncClient", return_value=mock_cm):
        job_id = await provider.submit_generation(gen)
        import asyncio
        await asyncio.sleep(0.3)

        with pytest.raises(RemoteWANGenerationFailedException) as exc_info:
            await provider.check_status(job_id)
        
        assert "NameError" in str(exc_info.value) or "500" in str(exc_info.value)

